#!/bin/bash
# Run a child `claude` with the parent session's identity/memory/effort env stripped, so each arm is a clean, isolated session.
exec env -u CLAUDE_CODE_SESSION_ID -u CLAUDE_CODE_REMOTE_SESSION_ID -u CLAUDE_EFFORT -u CLAUDE_ADDITIONAL_DIRECTORIES \
 -u CLAUDE_CODE_ADDITIONAL_DIRECTORIES_CLAUDE_MD -u CLAUDE_AFTER_LAST_COMPACT -u CLAUDE_AUTOCOMPACT_PCT_OVERRIDE \
 -u CLAUDE_CODE_TEE_SDK_STDOUT -u CLAUDE_CODE_DIAGNOSTICS_FILE -u CLAUDE_CODE_MESSAGING_SOCKET -u CLAUDE_CODE_MESSAGING_TOKEN \
 -u CLAUDE_CODE_SYNC_SESSION_REFS -u CLAUDE_CODE_POST_FOR_SESSION_INGRESS_V2 -u CLAUDE_CODE_CHILD_SESSION -u CLAUDECODE -u CLAUDE_PID \
 claude "$@"
